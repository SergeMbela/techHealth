    id_pollution INT IDENTITY(1,1) PRIMARY KEY,
    Ville NVARCHAR(100),
    DateMesure DATE,
    PM25 FLOAT,  -- Fine particulate matter (μg/m³)
    PM10 FLOAT,  -- Coarse particulate matter (μg/m³)
